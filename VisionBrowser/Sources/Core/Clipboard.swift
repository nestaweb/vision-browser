import Foundation

/// Un élément de l'historique du presse-papier (F3).
struct ClipboardItem: Equatable, Sendable, Identifiable {
    enum Kind: String, Sendable {
        case text
        case link
        /// Mot de passe, code à usage unique… : masqué, jamais écrit sur disque, expire vite.
        case secret
    }

    var id = UUID()
    var kind: Kind
    var text: String
    /// Application ou origine de la copie (« Bitwarden », « Notes », un site…).
    var source: String?
    var copiedAt: Date
    var fromBitwarden = false

    var url: URL? { kind == .link ? URL(string: text) : nil }
}

/// Ce que le presse-papier contient au moment de la lecture (sans AppKit : testable).
struct PasteboardContent: Sendable {
    var types: [String]
    var string: String?
    /// Application qui a écrit dans le presse-papier, si elle l'indique (`org.nspasteboard.source`).
    var declaredSource: String?
}

/// Règles de capture : quoi garder, et comment le classer.
enum ClipboardPolicy {
    static let concealedType = "org.nspasteboard.ConcealedType"
    static let transientType = "org.nspasteboard.TransientType"
    static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    /// Au-delà, le texte est tronqué : l'historique sert à retrouver, pas à archiver des documents.
    static let maxLength = 20_000

    /// - Parameter fromBitwarden: la copie a eu lieu pendant que le popup Bitwarden était ouvert.
    static func classify(_ content: PasteboardContent, fromBitwarden: Bool = false, source: String? = nil,
                         now: Date = Date()) -> ClipboardItem? {
        let types = Set(content.types)
        if types.contains(transientType) || types.contains(autoGeneratedType) { return nil }
        guard var text = content.string, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        if text.count > maxLength { text = String(text.prefix(maxLength)) }
        let source = fromBitwarden ? "Bitwarden" : (content.declaredSource ?? source)

        let kind: ClipboardItem.Kind
        if fromBitwarden || types.contains(concealedType) || isOneTimeCode(text) || looksLikePassword(text) {
            kind = .secret
        } else if isLink(text) {
            kind = .link
            text = text.trimmingCharacters(in: .whitespacesAndNewlines)
        } else {
            kind = .text
        }
        return ClipboardItem(kind: kind, text: text, source: source, copiedAt: now, fromBitwarden: fromBitwarden)
    }

    /// Code à usage unique (TOTP) : 6 à 8 chiffres, éventuellement coupés par une espace (« 123 456 »).
    static func isOneTimeCode(_ text: String) -> Bool {
        let digits = text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: " ", with: "")
        return (6...8).contains(digits.count) && digits.allSatisfy(\.isASCII) && digits.allSatisfy(\.isNumber)
    }

    /// Chaîne qui a l'allure d'un mot de passe : un seul « mot », ni lien ni adresse e-mail, qui mélange
    /// au moins trois sortes de caractères (avec un symbole dès 8 caractères, sans symbole à partir de 12).
    /// Mieux vaut masquer à tort un identifiant technique que garder un mot de passe en clair sur disque.
    static func looksLikePassword(_ text: String) -> Bool {
        let value = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard (8...128).contains(value.count), !value.contains(where: \.isWhitespace), !isLink(value) else { return false }
        if value.range(of: #"^[^@\s]+@[^@\s]+\.[A-Za-z]{2,}$"#, options: .regularExpression) != nil { return false }
        let lower = value.contains(where: \.isLowercase), upper = value.contains(where: \.isUppercase)
        let digits = value.filter(\.isNumber).count
        // Les séparateurs courants (noms de fichiers, références) ne comptent pas comme des symboles.
        let symbol = value.contains { !$0.isLetter && !$0.isNumber && !"_-./".contains($0) }
        let kinds = [lower, upper, digits > 0, symbol].filter { $0 }.count
        if symbol { return kinds >= 3 }
        return kinds >= 3 && value.count >= 12 && digits >= 2
    }

    /// Un lien web complet, seul sur sa ligne.
    static func isLink(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme), url.host() != nil else { return false }
        return true
    }
}

/// L'historique en mémoire : dédoublonnage, limites, expiration, recherche.
struct ClipboardHistory: Sendable {
    static let maxItems = 500
    /// Durée de vie d'un secret (réglable pour les essais : `-VBSecretLifetimeSeconds 30`).
    static var secretLifetime: TimeInterval {
        let value = UserDefaults.standard.double(forKey: "VBSecretLifetimeSeconds")
        return value > 0 ? value : 10 * 60
    }
    static let itemLifetime: TimeInterval = 30 * 24 * 3600

    /// Du plus récent au plus ancien.
    private(set) var items: [ClipboardItem] = []

    init(items: [ClipboardItem] = []) { self.items = items.sorted { $0.copiedAt > $1.copiedAt } }

    /// Ajoute un élément. Un contenu déjà présent remonte en tête (avec la nouvelle date) au lieu d'être dupliqué.
    /// Renvoie l'élément retenu.
    @discardableResult
    mutating func add(_ item: ClipboardItem) -> ClipboardItem {
        var kept = item
        if let index = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text }) {
            kept.id = items[index].id
            if kept.source == nil { kept.source = items[index].source }
            items.remove(at: index)
        }
        items.insert(kept, at: 0)
        if items.count > Self.maxItems { items.removeLast(items.count - Self.maxItems) }
        return kept
    }

    mutating func remove(_ id: UUID) { items.removeAll { $0.id == id } }

    /// Applique les règles actuelles aux éléments déjà gardés : ce qui ressemble désormais à un secret
    /// le devient (et quittera le disque). Renvoie les identifiants reclassés.
    @discardableResult
    mutating func reclassifySecrets() -> [UUID] {
        var changed: [UUID] = []
        for index in items.indices where items[index].kind != .secret
            && (ClipboardPolicy.looksLikePassword(items[index].text) || ClipboardPolicy.isOneTimeCode(items[index].text)) {
            items[index].kind = .secret
            changed.append(items[index].id)
        }
        return changed
    }

    /// Retire les secrets expirés et les éléments trop anciens. Renvoie les identifiants retirés.
    @discardableResult
    mutating func purge(now: Date, secretLifetime: TimeInterval = secretLifetime,
                        itemLifetime: TimeInterval = itemLifetime) -> [UUID] {
        let expired = items.filter { item in
            now.timeIntervalSince(item.copiedAt) >= (item.kind == .secret ? secretLifetime : itemLifetime)
        }.map(\.id)
        items.removeAll { expired.contains($0.id) }
        return expired
    }

    /// Recherche : tous les mots doivent apparaître (sans accents). Un secret n'est jamais cherché dans son
    /// contenu, seulement par son origine et par les mots « mot de passe », « code », « bitwarden ».
    func search(_ query: String, limit: Int = 4) -> [ClipboardItem] {
        let words = TabOrganizer.normalize(query).split(separator: " ").map(String.init)
        guard !words.isEmpty else { return [] }
        let everything = Self.wantsEverything(words)
        return Array(items.filter { item in
            if everything { return true }
            let haystack: String
            switch item.kind {
            case .secret: haystack = TabOrganizer.normalize("mot de passe code secret \(item.source ?? "")")
            case .text, .link: haystack = TabOrganizer.normalize("\(item.text) \(item.source ?? "")")
            }
            return words.allSatisfy { haystack.contains($0) }
        }.prefix(everything ? 8 : limit))
    }

    /// « presse », « copie », « clipboard » : tout l'historique récent.
    static func wantsEverything(_ words: [String]) -> Bool {
        let keywords = ["presse", "papier", "presse-papier", "copie", "copies", "copier", "clipboard"]
        return words.allSatisfy { word in word.count >= 3 && keywords.contains { $0.hasPrefix(word) } }
    }

    /// « à l'instant », « il y a 5 min », « il y a 2 h », « hier », « il y a 3 j ».
    static func age(of date: Date, now: Date = Date()) -> String {
        let seconds = max(0, now.timeIntervalSince(date))
        switch seconds {
        case ..<60: return "à l'instant"
        case ..<3600: return "il y a \(Int(seconds / 60)) min"
        case ..<86_400: return "il y a \(Int(seconds / 3600)) h"
        case ..<172_800: return "hier"
        default: return "il y a \(Int(seconds / 86_400)) j"
        }
    }

    /// Aperçu d'une ligne : jamais le contenu d'un secret.
    static func preview(of item: ClipboardItem, maxLength: Int = 90) -> String {
        if item.kind == .secret { return "••••••••" }
        let line = item.text.split(whereSeparator: \.isNewline).first.map(String.init) ?? item.text
        let collapsed = line.trimmingCharacters(in: .whitespaces)
        return collapsed.count > maxLength ? String(collapsed.prefix(maxLength)) + "…" : collapsed
    }
}

/// Stockage des éléments **non secrets** (SQLite). Les secrets ne quittent jamais la mémoire.
@MainActor
final class ClipboardStore {
    private let db: Database

    init(path: String) throws {
        db = try Database(path: path)
        try db.execute("""
            CREATE TABLE IF NOT EXISTS clips (
                id TEXT PRIMARY KEY, kind TEXT NOT NULL, text TEXT NOT NULL,
                source TEXT, copied_at REAL NOT NULL);
            CREATE INDEX IF NOT EXISTS clips_date ON clips(copied_at);
            """)
    }

    static func openDefault() -> ClipboardStore? {
        let url = AppPaths.applicationSupport.appendingPathComponent("clipboard.sqlite")
        do {
            try FileManager.default.createDirectory(at: AppPaths.applicationSupport, withIntermediateDirectories: true)
            // Dossier de l'app accessible à l'utilisateur seul : la base et ses fichiers annexes (-wal, -shm)
            // héritent de cette protection, comme l'historique de navigation.
            try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: AppPaths.applicationSupport.path)
            let store = try ClipboardStore(path: url.path)
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return store
        } catch {
            NSLog("Vision Browser : historique du presse-papier indisponible : \(error.localizedDescription)")
            return nil
        }
    }

    func load() -> [ClipboardItem] {
        var items: [ClipboardItem] = []
        try? db.run("SELECT id, kind, text, source, copied_at FROM clips ORDER BY copied_at DESC LIMIT ?",
                    [.integer(Int64(ClipboardHistory.maxItems))]) { row in
            guard let id = row.text(0).flatMap(UUID.init(uuidString:)), let kind = row.text(1).flatMap(ClipboardItem.Kind.init(rawValue:)),
                  kind != .secret, let text = row.text(2) else { return }
            items.append(ClipboardItem(id: id, kind: kind, text: text, source: row.text(3),
                                       copiedAt: Date(timeIntervalSinceReferenceDate: row.double(4))))
        }
        return items
    }

    /// Enregistre (ou met à jour) un élément ; un secret est refusé ici, par construction.
    func save(_ item: ClipboardItem) {
        guard item.kind != .secret else { return }
        let values: [Database.Value] = [.text(item.id.uuidString), .text(item.kind.rawValue), .text(item.text),
                                        item.source.map { .text($0) } ?? .null, .double(item.copiedAt.timeIntervalSinceReferenceDate)]
        try? db.run("INSERT OR REPLACE INTO clips (id, kind, text, source, copied_at) VALUES (?, ?, ?, ?, ?)", values)
    }

    func delete(_ ids: [UUID]) {
        for id in ids { try? db.run("DELETE FROM clips WHERE id = ?", [.text(id.uuidString)]) }
    }

    /// Garde les `maxItems` plus récents.
    func trim() {
        try? db.run("DELETE FROM clips WHERE id NOT IN (SELECT id FROM clips ORDER BY copied_at DESC LIMIT ?)",
                    [.integer(Int64(ClipboardHistory.maxItems))])
    }
}
