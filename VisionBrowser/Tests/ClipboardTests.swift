import XCTest
@testable import Vision_Browser

final class ClipboardPolicyTests: XCTestCase {
    private func content(_ text: String?, types: [String] = ["public.utf8-plain-text"]) -> PasteboardContent {
        PasteboardContent(types: types, string: text)
    }

    func testPlainTextAndLink() {
        XCTAssertEqual(ClipboardPolicy.classify(content("Factures à relancer"))?.kind, .text)
        let link = ClipboardPolicy.classify(content("  https://books.zoho.eu/app#/invoices \n"))
        XCTAssertEqual(link?.kind, .link)
        XCTAssertEqual(link?.url?.host(), "books.zoho.eu")
        XCTAssertEqual(ClipboardPolicy.classify(content("voir https://zoho.com demain"))?.kind, .text, "un lien dans une phrase reste du texte")
        XCTAssertEqual(ClipboardPolicy.classify(content("zoho.com"))?.kind, .text, "sans schéma, ce n'est pas un lien")
    }

    func testConcealedBitwardenAndCodesAreSecrets() {
        XCTAssertEqual(ClipboardPolicy.classify(content("hunter2", types: ["public.utf8-plain-text", ClipboardPolicy.concealedType]))?.kind, .secret)
        let fromBitwarden = ClipboardPolicy.classify(content("nesta@example.com"), fromBitwarden: true)
        XCTAssertEqual(fromBitwarden?.kind, .secret)
        XCTAssertEqual(fromBitwarden?.source, "Bitwarden")
        XCTAssertTrue(fromBitwarden?.fromBitwarden ?? false)
        XCTAssertEqual(ClipboardPolicy.classify(content("482 913"))?.kind, .secret, "code TOTP")
        XCTAssertEqual(ClipboardPolicy.classify(content("12345"))?.kind, .text, "5 chiffres : pas un code")
        XCTAssertEqual(ClipboardPolicy.classify(content("0612345678"))?.kind, .text, "10 chiffres : un numéro, pas un code")
    }

    func testPasswordLookingStringsAreSecrets() {
        for password in ["*3f7TK$83h@@^QM7tbpPV", "xK9mPq2LvR4nWz", "Zoho!2026", "aB3$efgh", "My-pass.2026"] {
            XCTAssertEqual(ClipboardPolicy.classify(content(password))?.kind, .secret, password)
        }
        for ordinary in ["Bonjour2026", "iPhone15Pro", "compta@exemple-a.fr", "https://zoho.com/A1b2C3!",
                         "deux mots!A1", "facture_2026-118", "MAJUSCULES", "README.md"] {
            XCTAssertNotEqual(ClipboardPolicy.classify(content(ordinary))?.kind, .secret, ordinary)
        }
    }

    func testIgnoredContent() {
        XCTAssertNil(ClipboardPolicy.classify(content("x", types: [ClipboardPolicy.transientType])))
        XCTAssertNil(ClipboardPolicy.classify(content("x", types: [ClipboardPolicy.autoGeneratedType])))
        XCTAssertNil(ClipboardPolicy.classify(content("  \n ")))
        XCTAssertNil(ClipboardPolicy.classify(content(nil, types: ["public.png"])), "image seule : hors champ")
    }

    func testLongTextIsTruncatedAndSourceKept() {
        let item = ClipboardPolicy.classify(PasteboardContent(types: [], string: String(repeating: "a", count: 30_000), declaredSource: "Notes"))
        XCTAssertEqual(item?.text.count, ClipboardPolicy.maxLength)
        XCTAssertEqual(item?.source, "Notes")
    }
}

final class ClipboardHistoryTests: XCTestCase {
    private let now = Date()

    private func item(_ text: String, _ kind: ClipboardItem.Kind = .text, ago: TimeInterval = 0, source: String? = nil) -> ClipboardItem {
        ClipboardItem(kind: kind, text: text, source: source, copiedAt: now.addingTimeInterval(-ago))
    }

    func testSameContentMovesToTopWithoutDuplicate() {
        var history = ClipboardHistory()
        let first = history.add(item("a", ago: 60, source: "Notes"))
        history.add(item("b", ago: 30))
        let again = history.add(item("a"))
        XCTAssertEqual(history.items.map(\.text), ["a", "b"])
        XCTAssertEqual(again.id, first.id, "même élément, identifiant conservé")
        XCTAssertEqual(again.source, "Notes", "l'origine connue est gardée")
        XCTAssertEqual(history.items.first?.copiedAt, now)
    }

    func testLimitKeepsMostRecent() {
        var history = ClipboardHistory()
        for i in 0..<(ClipboardHistory.maxItems + 5) { history.add(item("t\(i)")) }
        XCTAssertEqual(history.items.count, ClipboardHistory.maxItems)
        XCTAssertEqual(history.items.first?.text, "t\(ClipboardHistory.maxItems + 4)")
    }

    func testSecretsExpireFirst() {
        var history = ClipboardHistory(items: [item("pw", .secret, ago: 700), item("code", .secret, ago: 60),
                                               item("vieux", ago: 31 * 86_400), item("récent", ago: 86_400)])
        let removed = history.purge(now: now, secretLifetime: 600, itemLifetime: 30 * 86_400)
        XCTAssertEqual(removed.count, 2)
        XCTAssertEqual(history.items.map(\.text), ["code", "récent"])
    }

    func testOldPlainPasswordsAreReclassified() {
        var history = ClipboardHistory(items: [item("*3f7TK$83h@@^QM7tbpPV"), item("Facture Zoho n°42"), item("482913")])
        let changed = history.reclassifySecrets()
        XCTAssertEqual(changed.count, 2)
        XCTAssertEqual(history.items.map(\.kind), [.secret, .text, .secret])
    }

    func testSearchNeverLooksInsideSecrets() {
        let history = ClipboardHistory(items: [item("hunter2", .secret, source: "Bitwarden"), item("Facture Zoho n°42", ago: 10)])
        XCTAssertTrue(history.search("hunter").isEmpty, "le contenu d'un secret n'est pas cherchable")
        XCTAssertEqual(history.search("mot de passe").map(\.kind), [.secret])
        XCTAssertEqual(history.search("bitwarden").map(\.kind), [.secret])
        XCTAssertEqual(history.search("facture zoho").map(\.text), ["Facture Zoho n°42"])
        XCTAssertEqual(history.search("pres").count, 2, "« presse-papier » liste tout")
        XCTAssertTrue(history.search("").isEmpty)
    }

    func testAgeAndPreview() {
        XCTAssertEqual(ClipboardHistory.age(of: now.addingTimeInterval(-20), now: now), "à l'instant")
        XCTAssertEqual(ClipboardHistory.age(of: now.addingTimeInterval(-5 * 60), now: now), "il y a 5 min")
        XCTAssertEqual(ClipboardHistory.age(of: now.addingTimeInterval(-2 * 3600), now: now), "il y a 2 h")
        XCTAssertEqual(ClipboardHistory.age(of: now.addingTimeInterval(-30 * 3600), now: now), "hier")
        XCTAssertEqual(ClipboardHistory.age(of: now.addingTimeInterval(-3 * 86_400), now: now), "il y a 3 j")
        XCTAssertEqual(ClipboardHistory.preview(of: item("hunter2", .secret)), "••••••••")
        XCTAssertEqual(ClipboardHistory.preview(of: item("  ligne 1\nligne 2")), "ligne 1")
    }
}

@MainActor
final class ClipboardStoreTests: XCTestCase {
    func testSecretsAreNeverWritten() throws {
        let store = try ClipboardStore(path: ":memory:")
        let date = Date(timeIntervalSinceReferenceDate: 800_000_000)
        let text = ClipboardItem(kind: .link, text: "https://zoho.com", source: "Notes", copiedAt: date)
        store.save(text)
        store.save(ClipboardItem(kind: .secret, text: "hunter2", source: "Bitwarden", copiedAt: date))
        XCTAssertEqual(store.load(), [text])
        store.delete([text.id])
        XCTAssertEqual(store.load(), [])
    }
}
